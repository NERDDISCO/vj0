#!/usr/bin/env python3
"""Aggregate one completed saved formal app cohort. No live clients or network.
Requires the independent audit JSON, generated by bench/audit_app.py. Writes
JSON, Markdown and a CSV with every boundary/trial, without filtering tails.
"""
import argparse
import collections
import csv
import datetime
import hashlib
import json
from pathlib import Path
import re
import statistics


def span(values):
    return {'count': len(values), 'median': statistics.median(values), 'min': min(values), 'max': max(values), 'values': values} if values else {'count': 0, 'median': None, 'min': None, 'max': None, 'values': []}


def aggregate(audit, audit_path):
    trials = audit['trials']
    groups = collections.defaultdict(list)
    problems = []
    for trial in trials:
        match = re.fullmatch(r'(before|compute-capture|latest-input)-(512|768|1024)-r([01])', trial['name'])
        if not match:
            problems.append('Unexpected formal trial name: ' + trial['name'])
            continue
        arm = match[1]
        config = trial['config']
        expected_config = {'activeWorkers': 1, 'workerThreads': 128, 'sendFps': 60,
                           'variant': 'combined' if arm == 'before' else 'terminal-noop',
                           'outputCast': 'cpu' if arm == 'before' else 'gpu',
                           'mailbox': arm == 'latest-input', 'seconds': 60,
                           'height': {512: 288, 768: 448, 1024: 576}[int(match[2])]}
        for key, value in expected_config.items():
            if config.get(key) != value:
                problems.append(trial['name'] + ': unmatched ' + key)
        groups[(int(match[2]), arm)].append((int(match[3]), trial))
    expected = {(width, arm) for width in (512, 768, 1024) for arm in ('before', 'compute-capture', 'latest-input')}
    if set(groups) != expected:
        problems.append('The 3-resolution by 3-arm grid is incomplete')
    if len(trials) != 18 or audit['planned_trials'] != 18:
        problems.append('Formal cohort does not contain 18 planned and completed records')
    if audit['status'] != 'complete_passed':
        problems.append('Independent source audit did not finish with all gates passed')
    if not audit['comparisons']['completed_counterbalanced_cohort']:
        problems.append('Completed reverse-order counterbalance is not verified')
    if audit['provenance']['status'] != 'saved_provenance_checked':
        problems.append('Saved source/runtime/build provenance is not verified')
    arms, flattened = [], []
    for width in (512, 768, 1024):
        for arm in ('before', 'compute-capture', 'latest-input'):
            members = sorted(groups.get((width, arm), []))
            if [r for r, t in members] != [0, 1]:
                problems.append(f'{arm} {width}: exactly repeats 0 and 1 are required')
            item = {'width': width, 'arm': arm, 'trial_names': [t['name'] for r, t in members], 'boundaries': {}, 'per_trial': []}
            for key in ('main/sent', 'main/received', 'main/preview-image-raf', 'stage/webgl-frame-submitted'):
                bs = [t.get('boundaries', {}).get(key) for r, t in members]
                if any(b is None for b in bs):
                    problems.append(f'{arm} {width}: missing {key}')
                    continue
                item['boundaries'][key] = {'trial_fps': span([b['fps'] for b in bs]),
                    'trial_p95_age_ms': span([b['age_ms']['p95'] for b in bs if b['age_ms']['p95'] is not None]),
                    'trial_p99_age_ms': span([b['age_ms']['p99'] for b in bs if b['age_ms']['p99'] is not None]),
                    'trial_max_age_ms': span([b['age_ms']['max'] for b in bs if b['age_ms']['max'] is not None]),
                    'trial_max_gap_ms': span([b['max_event_gap_ms'] for b in bs])}
                for (repeat, trial), boundary in zip(members, bs):
                    row = {'trial': trial['name'], 'width': width, 'arm': arm, 'repeat': repeat,
                           'boundary': key, 'audit_status': trial['audit_status'], 'raw_status': trial['raw_status'],
                           'seconds': trial['elapsed_seconds'], 'frames': boundary['unique_frames'], 'fps': boundary['fps'],
                           'age_p50_ms': boundary['age_ms']['p50'], 'age_p95_ms': boundary['age_ms']['p95'],
                           'age_p99_ms': boundary['age_ms']['p99'], 'age_max_ms': boundary['age_ms']['max'],
                           'max_event_gap_ms': boundary['max_event_gap_ms'], 'final_silence_ms': boundary['final_silence_ms']}
                    for limit in (250, 500, 1000):
                        q = boundary['age_over_ms'][str(limit)]
                        row['frames_over_' + str(limit) + 'ms'] = q['frames']
                        row['percent_over_' + str(limit) + 'ms'] = q['percent']
                    flattened.append(row)
            for repeat, t in members:
                item['per_trial'].append({'name': t['name'], 'repeat': repeat, 'config': t['config'], 'seconds': t['elapsed_seconds'],
                                          'audit_status': t['audit_status'], 'raw_status': t['raw_status'], 'raw_problems': t['raw_problems'],
                                          'worker_activity': t['worker_activity'], 'audio_rms': t['audio_rms'], 'ordering': t['ordering'],
                                          'episodes': t['episodes']})
            arms.append(item)
    paired = collections.defaultdict(list)
    for p in audit['comparisons']['matched_pairs']:
        arm = 'compute-capture versus before' if p['left'].startswith('before-') else 'latest-input versus compute-capture'
        paired[(p['width'], arm)].append(p)
    changes = [{'width': width, 'comparison': name, 'stage_fps_change_pct': span([p['stage_fps_change_pct'] for p in sorted(values, key=lambda p: p['repeat'])]), 'pairs': sorted(values, key=lambda p: p['repeat'])}
               for (width, name), values in sorted(paired.items())]
    stage_by_trial = {r['trial']: r for r in flattened if r['boundary'] == 'stage/webgl-frame-submitted'}
    direction_counts = {}
    for label in ('compute-capture versus before', 'latest-input versus compute-capture'):
        pairs = [p for change in changes if change['comparison'] == label for p in change['pairs']]
        direction_counts[label] = {'pairs': len(pairs),
            'stage_fps_increased': sum(p['stage_fps_change_pct'] > 0 for p in pairs),
            'stage_p95_age_decreased': sum(stage_by_trial[p['right']]['age_p95_ms'] < stage_by_trial[p['left']]['age_p95_ms'] for p in pairs),
            'stage_p99_age_decreased': sum(stage_by_trial[p['right']]['age_p99_ms'] < stage_by_trial[p['left']]['age_p99_ms'] for p in pairs)}
    return {'created_utc': datetime.datetime.now(datetime.timezone.utc).isoformat(),
            'status': 'complete_verified_formal_cohort' if not problems else 'incomplete_or_failed_formal_cohort',
            'problems': problems, 'input_audit': str(audit_path), 'input_audit_sha256': hashlib.sha256(audit_path.read_bytes()).hexdigest(),
            'aggregation_script_sha256': hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
            'cohort_root': audit['root'], 'trials': len(trials), 'arms': arms, 'paired_changes': changes, 'paired_direction_counts': direction_counts, 'all_boundaries': flattened,
            'counterbalance': audit['comparisons']['sequences'], 'identity': audit['identity'],
            'provenance': audit['provenance'], 'cleanup': audit['cleanup'],
            'definitions': {'fps': 'Unique source frames divided by each trial common observed main/stage interval. Input is the achieved app send rate.',
                            'aggregation': 'Each arm has two trials. Median is the midpoint of the two trial values; min/max retain their spread. No pooling, outlier removal or averaging percentile samples into a pooled percentile.',
                            'paired_changes': 'Compute a relative FPS change within each same-resolution, same-repeat pair, then show the median and range of those two percentages. This differs from taking a ratio of arm median FPS.',
                            'tails': 'Every trial receive, preview RAF and stage p95/p99/max plus age fractions remain in CSV/JSON. Arm-level median p95/p99 means the median of per-trial percentiles, not a pooled percentile.',
                            'presentation': 'Preview means the current loaded image observed during RAF; stage means a WebGL submission. Neither proves compositor or physical display presentation.',
                            'age': 'JPEG encode initiation to observed boundary, excluding audio acquisition and physical presentation.',
                            'comparison': 'Within this one-GPU Torch 2.11/native-128-thread cohort only. Before-to-compute-capture combines capture scheduling, terminal compute skip and GPU output conversion changes. Latest-input changes admission/mailbox policy relative to that candidate. Sequential reversed-order repeats reduce one simple order confound but do not isolate features or remove WAN variation.',
                            'drain': 'Inter-trial drain proves observed encoder and worker quiescence only, not that SCTP contains no queued JPEG. Client epochs and 40-frame warmup limit stale-session effects; these records do not establish cross-trial contamination.',
                            'continuity': 'Passing final freshness and at-most-2-second worker-stat arrival gaps does not impose a frame-age tail bound.',
                            'cohorts': 'Interrupted observations, startup failure, and later three-minute soaks remain separate; no failed or high-tail trial was replaced or folded into another cohort.'}}


def md(data):
    def f(v, digits=2): return '—' if v is None else f'{v:.{digits}f}'
    def value_span(v): return f"{f(v['median'])} [{f(v['min'])}, {f(v['max'])}]"
    lines = ['# Formal app WAN comparison audit', '',
             f"Status: {data['status']}. {data['trials']} trials retained, with both repeat orders preserved.", '',
             data['definitions']['comparison'], '', data['definitions']['aggregation'], '',
             '| Resolution | Arm | Input FPS median [range] | Receive FPS median [range] | Preview RAF FPS median [range] | Stage GL FPS median [range] |',
             '|---|---|---:|---:|---:|---:|']
    for a in data['arms']:
        cells = [value_span(a['boundaries'].get(k, {}).get('trial_fps', span([]))) for k in ('main/sent', 'main/received', 'main/preview-image-raf', 'stage/webgl-frame-submitted')]
        lines.append('| ' + ' | '.join([str(a['width']), a['arm']] + cells) + ' |')
    for label, counts in data['paired_direction_counts'].items():
        lines += ['', f"{label}: stage FPS increased in {counts['stage_fps_increased']}/{counts['pairs']} matched pairs; stage p95 age decreased in {counts['stage_p95_age_decreased']}/{counts['pairs']}, and p99 age decreased in {counts['stage_p99_age_decreased']}/{counts['pairs']}. These count observed directions, not statistically established effects."]
    lines += ['', '| Resolution | Matched comparison | Stage FPS change %, repeat 0 / repeat 1 | Median [range] % |', '|---|---|---:|---:|']
    for c in data['paired_changes']:
        lines.append(f"| {c['width']} | {c['comparison']} | {' / '.join(f(v) for v in c['stage_fps_change_pct']['values'])} | {value_span(c['stage_fps_change_pct'])} |")
    lines += ['', 'Every trial tail is shown below. A higher FPS observation does not establish consistently fresher frames or a universal mailbox benefit.', '',
              '| Trial | Receive p95 / p99 ms | Preview RAF p95 / p99 ms | Stage p95 / p99 / max ms | Stage >250 / >500 / >1000 ms % |',
              '|---|---:|---:|---:|---:|']
    by_trial = collections.defaultdict(dict)
    for r in data['all_boundaries']:by_trial[r['trial']][r['boundary']] = r
    for a in data['arms']:
        for name in a['trial_names']:
            bs = by_trial[name]; cols = []
            for key in ('main/received', 'main/preview-image-raf', 'stage/webgl-frame-submitted'):
                b=bs.get(key,{})
                cols.append(' / '.join(f(b.get(field),1) for field in (('age_p95_ms','age_p99_ms','age_max_ms') if key.startswith('stage/') else ('age_p95_ms','age_p99_ms'))))
            stage=bs.get('stage/webgl-frame-submitted',{})
            cols.append(' / '.join(f(stage.get('percent_over_'+str(t)+'ms'),3) for t in (250,500,1000)))
            lines.append('| '+ ' | '.join([name]+cols)+' |')
    lines += ['', 'Retained high-age receive episodes:', '']
    any_episode=False
    for a in data['arms']:
        for t in a['per_trial']:
            e=t['episodes']
            if not e['groups']:continue
            any_episode=True
            peak=max((g['peak'] for g in e['groups']),key=lambda v:v['age_ms'])
            lines.append(f"- {t['name']}: {e['frames_above_threshold']} receipts above {f(e['threshold_ms'],0)} ms across {len(e['groups'])} consecutive groups; peak {f(peak['age_ms'],1)} ms at {f(peak['receive_relative_s'],3)} seconds, frame {peak['id']}. No outlier was removed.")
    if not any_episode:lines.append('No receipt exceeded the configured episode threshold in this cohort.')
    lines += ['', data['definitions']['presentation'], '', data['definitions']['age'], '', data['definitions']['continuity'], '',
              data['definitions']['drain'], '', data['definitions']['cohorts'], '',
              'Runtime, source hashes, served build identities, worker IDs, source/capture ordering, audio levels and measurement arithmetic are bound to the saved independent audit. Provenance checks compare saved artifacts; they do not query live hosts.', '',
              'The companion CSV contains all 72 trial/boundary rows, including frame counts, observed seconds, achieved rates, tails and final/maximum gaps.']
    if data['problems']:lines+=['','Unresolved audit problems:','']+['- '+v for v in data['problems']]
    return '\n'.join(lines)+'\n'


def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--audit',type=Path,required=True);p.add_argument('--output',type=Path,required=True);p.add_argument('--allow-incomplete',action='store_true');args=p.parse_args()
    audit=json.loads(args.audit.read_text());data=aggregate(audit,args.audit)
    if data['problems'] and not args.allow_incomplete:
        p.error('; '.join(data['problems']))
    args.output.parent.mkdir(parents=True,exist_ok=True)
    args.output.write_text(json.dumps(data,indent=2)+'\n');args.output.with_suffix('.md').write_text(md(data))
    with args.output.with_suffix('.csv').open('w',newline='') as f:
        rows=data['all_boundaries'];writer=csv.DictWriter(f,fieldnames=list(rows[0]) if rows else ['trial'],lineterminator='\n');writer.writeheader();writer.writerows(rows)
    print(data['status'],len(data['all_boundaries']),'boundary rows')
    return 0 if not data['problems'] else 1

if __name__=='__main__':raise SystemExit(main())
